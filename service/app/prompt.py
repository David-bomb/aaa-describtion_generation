import json
from typing import Any


PROMPT_TEMPLATE = """Ты пишешь товарное описание для объявления на Авито на русском языке.

# Главный принцип
Это описание товара для покупателя, а не подпись к фотографии и не рекламный текст с догадками. Нужно ясно описать, что продаётся, в каком состоянии товар и какие характеристики указаны во входных данных.

Каждое утверждение должно опираться на один из источников:
1. `title`;
2. `category_name`;
3. `params`;
4. товарно-значимая деталь самого товара, которую прямо видно на фотографии.

Если утверждение нельзя проверить по этим данным — не пиши его. Лучше коротко перечислить подтверждённые свойства, чем добавлять красивую неподтверждённую фразу.

# Что тебе дано
1. **Фотография товара** (одно изображение).
2. **Заголовок объявления** (`title`).
3. **Категория** (`category_name`).
4. **Характеристики** (`params`) — JSON-словарь со структурированными свойствами. Ключи не нормализованы: могут быть в форматах `с_подчёркиваниями`, `camelCase` или `с пробелами`. Используй их по смыслу.

# Что нужно написать
Один абзац с товарным описанием:
- начни с предмета продажи: тип товара, бренд, модель, версия, порода или категория — по `title` и `params`;
- укажи состояние и 2–4 ключевые характеристики из `params`, если они есть;
- используй фото только для важных свойств самого товара: цвет, материал, комплектность, заметные дефекты, общий внешний вид товара;
- если фото даёт только фон/сцену/ракурс, игнорируй эти детали.

# Как использовать фото
Фото помогает уточнить свойства товара, но не должно превращать ответ в описание картинки.

Используй максимум 1–2 визуальных признака и только если они важны покупателю: цвет/окрас, материал, явная комплектность, явный дефект. Если визуальная деталь сомнительна или не влияет на покупку — пропусти её.

Пиши факт напрямую: «белый корпус», «зелёная дверь», «дымчато-серый окрас». Не ссылайся на источник факта.

Нельзя писать:
- «на фото видно», «на фото виден», «видны», «указано», «указаны», «по описанию», «лежит», «стоит», «держат в руках»;
- фон, покрывало, стол, пол, гараж, склад, руки, позу, ракурс, освещение, монитор рядом, поверхность под товаром;
- очевидные мелочи вроде логотипа, вентиляционных решёток, складок фона, если это не ключевая характеристика товара.

# Запрещённые неподтверждённые выводы
- НЕ пиши «подходит», «подойдёт», «для дома», «для гаража», «для игр», «для установки», если это прямо не указано в `title` или `params`.
- НЕ пиши «без повреждений», «без дефектов», «отличное внешнее состояние», «полный комплект», «оригинальный контроллер», «дверь в сборе», «без стекла», «без ручки», если это прямо не указано в `params` или `title`.
- НЕ добавляй пустые общие фразы: «товар предназначен для использования», «подойдёт для покупки», «хороший вариант», «можно использовать по назначению».
- Для животных НЕ пиши про здоровье, активность, характер, адаптацию, лоток, питание, прививки или готовность к переезду, если этого нет в `params` или `title`.
- Для электроники НЕ пиши про работоспособность сверх того, что указано в `params`; если есть `состояние`, повтори его без расширения.
- Для автозапчастей НЕ додумывай совместимость, комплектность, наличие/отсутствие стекла, ручек, креплений или историю использования, если этого нет во входных данных.

# Общие запреты
- НЕ додумывай сценарии использования, хранения, перевозки, ремонта, подарка или перепродажи.
- НЕ приписывай товару качество, выгоду или эмоцию: «удобный», «практичный», «надёжный», «отличный вариант», «как новый», если это не подтверждено `params` или фото.
- НЕ упоминай цену, скидки, способы оплаты, доставку, гарантии, контакты, ссылки, Telegram, WhatsApp, соцсети.
- НЕ используй emoji, markdown-разметку, заголовки, маркированные списки.
- НЕ повторяй `title` дословно как первую фразу.
- НЕ пиши «Здравствуйте» / «Уважаемые покупатели».

# Стиль и длина
Стиль спокойный и естественный, как у продавца, который аккуратно перечисляет подтверждённые свойства товара. Без рекламных украшений. Не более 70 слов. Если данных мало — можно написать одно короткое предложение. Не добавляй финальную фразу ради красоты.

# Формат вывода
Выдай только текст описания. Без префикса «Описание:», без пояснений и рассуждений.

# Данные товара
**title:** {title}
**category_name:** {category_name}
**params:** {params}

Напиши описание."""


def parse_params_json(raw_params: str | None) -> dict[str, Any]:
    if raw_params is None or not raw_params.strip():
        return {}

    try:
        parsed = json.loads(raw_params)
    except json.JSONDecodeError as exc:
        raise ValueError("params must be a valid JSON object") from exc

    if not isinstance(parsed, dict):
        raise ValueError("params must be a JSON object")

    return parsed


def render_params(params: dict[str, Any] | None) -> str:
    return json.dumps(params or {}, ensure_ascii=False, sort_keys=True, separators=(",", ": "))


def render_prompt(title: str, category_name: str, params: dict[str, Any] | None) -> str:
    return PROMPT_TEMPLATE.format(
        title=title.strip(),
        category_name=category_name.strip(),
        params=render_params(params),
    )
